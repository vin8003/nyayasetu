export function p(lang: OutputLang) {
	return appCopy[lang];
}

/** Fill {placeholders} in a copy string. */
export function fill(template: string, values: Record<string, string | number>) {
	return template.replace(/\{(\w+)\}/g, (_, key) => (key in values ? String(values[key]) : `{${key}}`));
}

export function originLabel(lang: OutputLang, origin: Origin) {
	const c = p(lang);
	if (origin === "court_direction") return c.originCourt;
	if (origin === "statute") return c.originStatute;
	if (origin === "ai_inference" || origin === "ai_suggestion") return c.originAi;
	if (origin === "system") return c.originSystem;
	return c.originLawyer;
}

